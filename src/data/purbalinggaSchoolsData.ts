export function findSchoolByName(input: string): SchoolReference | null {
  if (!input || typeof input !== 'string') return null;
  const normalized = input.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim();
  if (!normalized) return null;

  // Exact or keyword match
  for (const school of PURBALINGGA_SCHOOLS) {
    if (school.name.toLowerCase() === input.toLowerCase().trim()) {
      return school;
    }
    for (const kw of school.keywords) {
      const cleanKw = kw.toLowerCase().replace(/[^a-z0-9]/g, ' ').replace(/\s+/g, ' ').trim();
      if (normalized === cleanKw || normalized.includes(cleanKw) || cleanKw.includes(normalized)) {
        return school;
      }
    }
  }
  return null;
}
